'use strict';
const fs = require('fs');
const path = require('path');
const root = process.cwd();
const twilight = JSON.parse(fs.readFileSync(path.join(root, 'twilight.json'), 'utf8').replace(/^\uFEFF/, ''));
const id = 'veloura_cart_banners_columns_2026';
const defs = twilight.settings.filter((item) => item && item.id === id);
if (defs.length !== 1) throw new Error(`${id} must appear once; found ${defs.length}`);
const setting = defs[0];
if (setting.format !== 'slider' || String(setting.minimum) !== '1' || String(setting.maximum) !== '3') throw new Error('Columns slider schema is invalid.');
const twig = fs.readFileSync(path.join(root, 'src/views/components/cart/veloura-cart-banners.twig'), 'utf8');
const scss = fs.readFileSync(path.join(root, 'src/assets/styles/05-utilities/veloura-cart-banners.scss'), 'utf8');
if (!twig.includes('veloura_cart_banners_columns_2026')) throw new Error('Twig columns setting is missing.');
if (!scss.includes('--veloura-cart-banner-columns')) throw new Error('SCSS columns variable is missing.');
if (!scss.includes("[data-position='after_checkout_button']")) throw new Error('Checkout spacing rule is missing.');
console.log('twilight.json: OK');
console.log('Cart banner columns slider: OK');
console.log('Checkout-button spacing: OK');
console.log('Cart Banners V2.5 verified successfully.');
